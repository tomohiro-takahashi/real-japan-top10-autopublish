def main() -> None:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    DIAG_DIR.mkdir(parents=True, exist_ok=True)

    # Step 1: Render all 8 Roman Empire diagrams (`diagram_01..08`) and 8 Question Cards (`q_01..08`)
    render_all_rome_diagrams(FLOW_DIR, DIAG_DIR)

    with tempfile.TemporaryDirectory(prefix="rome_cinema_") as tmp:
        work_dir = Path(tmp)
        long_segs: List[Path] = []
        beat_counter = 0

        for block in ROME_COMPLETE_BLOCKS:
            kind = block["kind"]
            chapter = block["chapter"]

            if kind == "diagram":
                diag_id = block["diagram_id"]
                diag_png = DIAG_DIR / f"{diag_id}.png"

                q_spec = ROME_QUESTION_BEAT_MAP.get(diag_id)
                if q_spec:
                    beat_counter += 1
                    q_png = DIAG_DIR / f"{q_spec['q_id']}.png"
                    q_wav = work_dir / f"beat_{beat_counter:03d}.wav"
                    q_dur = build_narration_beat_wav(
                        text=q_spec["narration"],
                        se_kind="question_sting",
                        out_wav=q_wav,
                        work_dir=work_dir,
                        beat_idx=beat_counter,
                    )
                    print(f"Beat {beat_counter:02d} (QUESTION {q_spec['q_id']}): {q_dur:.2f}s | {q_spec['sub_main']}", flush=True)
                    q_ov = work_dir / f"ov_{beat_counter:03d}.png"
                    render_cinema_overlay_16x9(chapter, q_spec["sub_top"], q_spec["sub_main"], q_ov, is_diagram=True)
                    q_seg = work_dir / f"seg_{beat_counter:03d}.mp4"
                    render_diagram_beat_segment(
                        diagram_png=q_png,
                        overlay_png=q_ov,
                        beat_wav=q_wav,
                        dur=q_dur,
                        zoom_dir="in",
                        out_mp4=q_seg,
                    )
                    long_segs.append(q_seg)

                for beat in block["beats"]:
                    beat_counter += 1
                    beat_wav = work_dir / f"beat_{beat_counter:03d}.wav"
                    dur = build_narration_beat_wav(
                        text=beat["narration"],
                        se_kind=beat["se"],
                        out_wav=beat_wav,
                        work_dir=work_dir,
                        beat_idx=beat_counter,
                    )
                    print(f"Beat {beat_counter:02d} (DIAGRAM {diag_id}): {dur:.2f}s | {beat['sub_main']}", flush=True)
                    ov_png = work_dir / f"ov_{beat_counter:03d}.png"
                    render_cinema_overlay_16x9(chapter, beat["sub_top"], beat["sub_main"], ov_png, is_diagram=True)
                    seg_mp4 = work_dir / f"seg_{beat_counter:03d}.mp4"
                    render_diagram_beat_segment(
                        diagram_png=diag_png,
                        overlay_png=ov_png,
                        beat_wav=beat_wav,
                        dur=dur,
                        zoom_dir=beat.get("zoom", "in"),
                        out_mp4=seg_mp4,
                    )
                    long_segs.append(seg_mp4)
            else:
                scene_id = block["scene_id"]
                flow_mp4 = resolve_rome_scene_mp4(scene_id)
                for beat in block["beats"]:
                    beat_counter += 1
                    beat_wav = work_dir / f"beat_{beat_counter:03d}.wav"
                    dur = build_narration_beat_wav(
                        text=beat["narration"],
                        se_kind=beat["se"],
                        out_wav=beat_wav,
                        work_dir=work_dir,
                        beat_idx=beat_counter,
                    )
                    print(
                        f"Beat {beat_counter:02d} (VIDEO {scene_id} -> {flow_mp4.name} [{beat['cam']}]): "
                        f"{dur:.2f}s | {beat['sub_main']}",
                        flush=True,
                    )
                    ov_png = work_dir / f"ov_{beat_counter:03d}.png"
                    render_cinema_overlay_16x9(chapter, beat["sub_top"], beat["sub_main"], ov_png, is_diagram=False)
                    seg_mp4 = work_dir / f"seg_{beat_counter:03d}.mp4"
                    render_beat_video_segment(
                        flow_mp4=flow_mp4,
                        overlay_png=ov_png,
                        beat_wav=beat_wav,
                        dur=dur,
                        cam_mode=beat["cam"],
                        clip_window=beat["clip_window"],
                        out_mp4=seg_mp4,
                    )
                    long_segs.append(seg_mp4)

        concat_long_txt = work_dir / "concat_long.txt"
        concat_long_txt.write_text("\n".join(f"file '{p}'" for p in long_segs))
        raw_long_mp4 = work_dir / "raw_long.mp4"
        subprocess.run(
            ["ffmpeg", "-y", "-f", "concat", "-safe", "0", "-i", str(concat_long_txt), "-c", "copy", str(raw_long_mp4)],
            check=True,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )
        for p in long_segs:
            p.unlink(missing_ok=True)
        for p in work_dir.glob("*.wav"):
            p.unlink(missing_ok=True)
        for p in work_dir.glob("*.png"):
            p.unlink(missing_ok=True)
        long_dur = get_duration(raw_long_mp4)
        bgm_long_wav = work_dir / "bgm_long.wav"
        generate_cinematic_history_bgm(16.0, bgm_long_wav)

        out_long = OUTPUT_DIR / "history_rome_fall_complete_long.mp4"
        tmp_out_long = work_dir / "final_rome_complete_long.mp4"
        subprocess.run(
            [
                "ffmpeg",
                "-y",
                "-i",
                str(raw_long_mp4),
                "-stream_loop",
                "-1",
                "-i",
                str(bgm_long_wav),
                "-filter_complex",
                f"[0:a]volume=1.18[va];[1:a]atrim=0:{long_dur+1.0:.2f},volume=0.28,afade=t=out:st={max(0.0, long_dur-3.0):.2f}:d=3.0[ba];[va][ba]amix=inputs=2:duration=first:dropout_transition=0[a]",
                "-map",
                "0:v",
                "-map",
                "[a]",
                "-c:v",
                "copy",
                "-c:a",
                "aac",
                "-b:a",
                "192k",
                str(tmp_out_long),
            ],
            check=True,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )
        tmp_out_long.replace(out_long)
        print(f"[DONE] Roman Empire Complete Long video: {out_long} ({long_dur:.1f}s = {long_dur/60:.1f} mins)", flush=True)

        out_thumb = OUTPUT_DIR / "history_rome_fall_thumb.jpg"
        if not out_thumb.exists():
            build_rome_thumbnail(out_thumb)
        print(f"[DONE] Roman Empire Thumbnail: {out_thumb}", flush=True)


if __name__ == "__main__":
    main()


def build_templar_thumbnail(out_jpg: Path) -> None:
    """
    Build the exact Proposal D thumbnail template (matching French Revolution & Roman Empire):
    - Right side: High-contrast close-up of Grand Master Jacques de Molay / Knights Templar (`scene_02.mp4`)
    - Left side: Dark obsidian backdrop with 3 '× 通説 → 真実' comparison cards
    - Top gold tag: `これ1本で完全理解【AI実写・全18分】`
    - Bottom giant impact title: `教科書の「通説」が覆る！` / `十字軍とテンプル騎士団`
    """
    from build_history_thumbnail_proposals import draw_stroked_text, get_font

    W, H = 1280, 720
    s2 = resolve_templar_scene_mp4("scene_02")
    f1_png = out_jpg.parent / "_tmp_templar_thumb_f1.png"

    subprocess.run(
        ["ffmpeg", "-y", "-ss", "2.0", "-i", str(s2), "-frames:v", "1", "-vf", "scale=1280:720", str(f1_png)],
        check=True,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    )

    col_rgb = Image.open(f1_png).convert("RGBA")
    col_rgb = ImageEnhance.Contrast(col_rgb).enhance(1.22)
    col_rgb = ImageEnhance.Brightness(col_rgb).enhance(1.08)
    col_rgb = ImageEnhance.Color(col_rgb).enhance(1.18)

    canvas = Image.new("RGBA", (W, H), (10, 12, 18, 255))
    # Shift Grand Master & Knights Templar scene to right half (x=540..1280)
    canvas.paste(col_rgb, (210, 0))

    # Left dark obsidian panel with smooth gradient blend (identical to Proposal D)
    ov = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    od = ImageDraw.Draw(ov, "RGBA")
    for x in range(780):
        if x < 540:
            a = 248
        else:
            a = int(248 * (1.0 - (x - 540) / 240.0) ** 1.3)
        od.line([(x, 0), (x, H)], fill=(10, 12, 18, a))

    for y in range(H - 220, H):
        a = int(235 * ((y - (H - 220)) / 220.0) ** 1.3)
        od.line([(0, y), (W, y)], fill=(6, 8, 12, a))

    # Top gold tag (identical position & style to Proposal D)
    od.rounded_rectangle((40, 34, 560, 90), radius=10, fill=(218, 175, 55, 245))
    od.text((58, 44), "これ1本で完全理解【AI実写・全18分】", font=get_font("sans", 27), fill=(12, 12, 16, 255))

    # Three "Myth vs Truth" cards on the left (identical coordinates & colors to Proposal D)
    cards = [
        ("× 聖地を守る清貧の騎士", "→ 世界初の「国際メガバンク」"),
        ("× イスラムと戦う純粋聖戦", "→ 第4回はキリスト教首都を略奪"),
        ("× 悪魔崇拝で13日金曜に処刑", "→ 仏王の借金踏み倒し＆冤罪"),
    ]
    cy = 115
    for myth, truth in cards:
        od.rounded_rectangle((40, cy, 620, cy + 108), radius=12, fill=(24, 28, 38, 235), outline=(218, 175, 55, 180), width=2)
        od.text((60, cy + 14), myth, font=get_font("sans", 27), fill=(255, 105, 105, 255))
        od.text((60, cy + 56), truth, font=get_font("sans", 31), fill=(255, 230, 110, 255))
        cy += 124

    canvas.alpha_composite(ov)

    # Bottom full-width impact title (identical typography & position to Proposal D)
    f_hook = get_font("sans", 52)
    draw_stroked_text(
        canvas,
        (42, H - 210),
        "教科書の「通説」が覆る！",
        f_hook,
        fill=(255, 255, 255, 255),
        stroke_fill=(0, 0, 0, 255),
        stroke_w=8,
    )

    f_title = get_font("sans", 84)
    draw_stroked_text(
        canvas,
        (38, H - 138),
        "十字軍とテンプル騎士団",
        f_title,
        fill=(255, 220, 70, 255),
        stroke_fill=(165, 15, 20, 255),
        stroke_w=10,
        glow_color=(0, 0, 0, 250),
    )

    canvas.convert("RGB").save(out_jpg, quality=95)
    f1_png.unlink(missing_ok=True)


